import {
  FollowMutationResult,
  FriendshipStatusSnapshot,
  ISocialGraphRepository,
} from '@/modules/social-graph/domain/repositories/social-graph.repository';
import {
  BadRequestException,
  ForbiddenException,
  NotFoundException,
} from '@nestjs/common';
import { FollowUserUseCase } from './follow-user.usecase';

const status: FriendshipStatusSnapshot = {
  following: true,
  outgoing_request: false,
  incoming_request: false,
  followed_by: false,
  is_bestie: false,
  is_private: false,
  is_restricted: false,
  is_feed_favorite: false,
  blocking: false,
  blocked_by: false,
};

describe('FollowUserUseCase', () => {
  let repository: jest.Mocked<ISocialGraphRepository>;
  let useCase: FollowUserUseCase;

  beforeEach(() => {
    repository = {
      follow: jest.fn(),
      unfollow: jest.fn(),
      acceptFollowRequest: jest.fn(),
      blockUser: jest.fn(),
      getFriendshipStatus: jest.fn(),
    };
    useCase = new FollowUserUseCase(repository);
  });

  it('rejects self-follow without calling persistence', async () => {
    await expect(useCase.execute('10', '10')).rejects.toBeInstanceOf(
      BadRequestException,
    );
    expect(repository.follow).not.toHaveBeenCalled();
  });

  it.each([
    ['FOLLOWING', true, false],
    ['REQUESTED', false, true],
  ] as const)(
    'returns the %s transition generated by the repository',
    async (kind, following, outgoingRequest) => {
      const result: FollowMutationResult = {
        kind,
        user: {
          id: '20',
          username: 'target',
          isPrivate: kind === 'REQUESTED',
        },
        friendshipStatus: {
          ...status,
          following,
          outgoing_request: outgoingRequest,
          is_private: kind === 'REQUESTED',
        },
      };
      repository.follow.mockResolvedValue(result);

      await expect(useCase.execute('10', '20')).resolves.toEqual(result);
      expect(repository.follow).toHaveBeenCalledWith('10', '20');
    },
  );

  it('maps a missing target to NotFoundException', async () => {
    repository.follow.mockResolvedValue({ kind: 'TARGET_NOT_FOUND' });

    await expect(useCase.execute('10', '20')).rejects.toBeInstanceOf(
      NotFoundException,
    );
  });

  it('maps a blocked relationship to ForbiddenException', async () => {
    repository.follow.mockResolvedValue({ kind: 'FOLLOW_FORBIDDEN' });

    await expect(useCase.execute('10', '20')).rejects.toBeInstanceOf(
      ForbiddenException,
    );
  });
});
