import {
  Entity,
  Column,
  PrimaryColumn,
  CreateDateColumn,
  UpdateDateColumn,
  ManyToOne,
  JoinColumn,
  Index,
} from 'typeorm';

import { UserEntity } from '@/modules/users/infrastructure/typeorm/user.entity';
import { ConversationEntity } from '@/modules/coversation/infrastructure/typeorm/conversation.entity';
import { MessageStatus, MessageType } from '@/shared/enums/message.enum';

@Entity('direct_messages')
@Index('idx_dm_thread_active_message', ['threadId', 'isDeleted', 'id'])
@Index('idx_thread_id', ['threadId', 'id'])
@Index('idx_thread_sender', ['threadId', 'senderFbid'])
@Index('idx_reply', ['replyToMessageId'])
@Index('uniq_thread_client_ctx', ['threadId', 'clientContext'], {
  unique: true,
})
export class MessageEntity {
  /* ==============================
   * Identity
   * ============================== */

  /**
   * message id
   * production system thường dùng snowflake id
   */
  @PrimaryColumn({
    name: 'message_id',
    type: 'bigint',
  })
  id!: string;

  /**
   * retry safe id generated by client
   */
  @Column({
    name: 'client_context',
    type: 'varchar',
    length: 64,
    nullable: false,
  })
  clientContext!: string;

  /* ==============================
   * Thread
   * ============================== */

  @Column({
    name: 'thread_id',
    type: 'bigint',
  })
  threadId!: string;

  @ManyToOne(() => ConversationEntity, (c) => c.messages, {
    onDelete: 'CASCADE',
  })
  @JoinColumn({ name: 'thread_id' })
  thread!: ConversationEntity;

  /* ==============================
   * Sender
   * ============================== */

  @Column({
    name: 'sender_fbid',
    type: 'bigint',
  })
  senderFbid!: string;

  @ManyToOne(() => UserEntity, {
    onDelete: 'RESTRICT',
  })
  @JoinColumn({ name: 'sender_fbid' })
  sender?: UserEntity;

  /* ==============================
   * Message Content
   * ============================== */

  @Column({
    name: 'content_type',
    type: 'enum',
    enum: MessageType,
  })
  contentType!: MessageType;

  /**
   * text message body
   */
  @Column({
    name: 'text_body',
    type: 'text',
    nullable: true,
  })
  textBody?: string;

  /**
   * preview snippet used in inbox
   */
  @Column({
    name: 'igd_snippet',
    type: 'text',
    nullable: true,
  })
  snippet?: string;

  /**
   * flexible content
   * media / share / link
   */
  @Column({
    type: 'json',
    nullable: true,
  })
  payload?: Record<string, any>;

  /* ==============================
   * Reply
   * ============================== */

  @Column({
    name: 'reply_to_message_id',
    type: 'bigint',
    nullable: true,
  })
  replyToMessageId?: string;

  @ManyToOne(() => MessageEntity, {
    nullable: true,
  })
  @JoinColumn({ name: 'reply_to_message_id' })
  replyTo?: MessageEntity;

  /* ==============================
   * Expiration
   * ============================== */

  @Column({
    name: 'expiration_timestamp_ms',
    type: 'bigint',
    nullable: true,
  })
  expirationTimestampMs?: number;

  @Column({
    name: 'view_expiration_timestamp_ms',
    type: 'bigint',
    nullable: true,
  })
  viewExpirationTimestampMs?: number;

  /* ==============================
   * Timestamp
   * ============================== */

  /**
   * millisecond timestamp
   */
  @Column({
    name: 'timestamp_ms',
    type: 'bigint',
  })
  timestampMs!: number;

  @Column({
    name: 'client_timestamp_ms',
    type: 'bigint',
    nullable: true,
  })
  clientTimestampMs?: number;

  @Column({
    name: 'edited_at',
    type: 'timestamp',
    nullable: true,
  })
  editedAt?: Date;

  @Column({
    name: 'is_edited',
    type: 'boolean',
    default: false,
  })
  isEdited!: boolean;

  /* ==============================
   * Global Delivery State
   * ============================== */

  /**
   * Global lifecycle state of this message.
   * SENT    = persisted, waiting to be delivered
   * FAILED  = could not be delivered (retry / alert)
   *
   * Delivery / read state per-participant is tracked in
   * conversation_watermarks.deliveryWatermarkTimestampMs
   * and conversation_watermarks.readWatermarkTimestampMs
   */
  @Column({
    name: 'status',
    type: 'enum',
    enum: MessageStatus,
    default: MessageStatus.SENT,
  })
  status!: MessageStatus;

  @Column({
    name: 'error_code',
    type: 'varchar',
    length: 255,
    nullable: true,
  })
  errorCode?: string;

  /* ==============================
   * Lifecycle
   * ============================== */

  @Column({
    name: 'is_deleted',
    type: 'boolean',
    default: false,
  })
  isDeleted!: boolean;

  @Column({
    name: 'deleted_at',
    type: 'timestamp',
    nullable: true,
  })
  deletedAt?: Date;

  @CreateDateColumn({
    name: 'created_at',
  })
  createdAt!: Date;

  @UpdateDateColumn({
    name: 'updated_at',
  })
  updatedAt!: Date;
}
